# Program to demonstrate type checking and built-in functions

a = 10
b = 5.5
c = "Hello"
d = [1, 2, 3]

print("Type of a:", type(a))
print("Type of b:", type(b))
print("Type of c:", type(c))
print("Type of d:", type(d))

print("Absolute value:", abs(-25))
print("Length of string:", len("Python"))
print("Minimum value:", min(10, 20, 5, 15))
print("Rounded value:", round(10.567, 2))
print("Is alphanumeric:", "Python123".isalnum())